CREATE TABLE print_requests (
    id             BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    -- Deleting a user deletes their requests (files on disk are removed by the application).
    owner_id       BIGINT        NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    name           VARCHAR(100)  NOT NULL,
    description    VARCHAR(2000),
    -- Set by the admin when reviewing (#5); NULL means "price pending".
    final_price    NUMERIC(10, 2) CHECK (final_price >= 0),
    -- All states of the full flow, so the review feature needs no migration for them.
    status         VARCHAR(16)   NOT NULL DEFAULT 'SUBMITTED'
                   CHECK (status IN ('SUBMITTED', 'IN_REVIEW', 'ACCEPTED', 'DECLINED', 'COMPLETED')),
    decline_reason VARCHAR(2000),
    created_at     TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ   NOT NULL DEFAULT now()
);

CREATE INDEX print_requests_owner_idx ON print_requests (owner_id, created_at DESC);
CREATE INDEX print_requests_created_idx ON print_requests (created_at DESC);

-- Separate table so a request can hold several files later; for now there is exactly one.
CREATE TABLE request_files (
    id                BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    request_id        BIGINT       NOT NULL REFERENCES print_requests (id) ON DELETE CASCADE,
    original_filename VARCHAR(255) NOT NULL,
    -- Relative to STORAGE_PATH; generated by the application, never from user input.
    storage_path      VARCHAR(255) NOT NULL UNIQUE,
    file_type         VARCHAR(16)  NOT NULL CHECK (file_type IN ('STL', 'THREE_MF')),
    size_bytes        BIGINT       NOT NULL CHECK (size_bytes > 0),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX request_files_request_idx ON request_files (request_id);
